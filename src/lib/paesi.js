export function nomePaese(codice, lingua = 'it') {
    try { return new Intl.DisplayNames([lingua], { type: 'region' }).of(codice) ?? codice } catch { return codice }
}

/** [{ codice, nome }] con il paese di casa in cima. */
export function elencoPaesi(lingua = 'it', casa = 'IT') {
    const altri = CODICI.filter(c => c !== casa)
        .map(codice => ({ codice, nome: nomePaese(codice, lingua) }))
        .sort((a, b) => a.nome.localeCompare(b.nome, lingua))
    return [{ codice: casa, nome: nomePaese(casa, lingua) }, ...altri]
}
